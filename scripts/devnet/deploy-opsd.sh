#!/usr/bin/env bash
# Deploy the ops signing service to one of the two validator hosts.
#
# There is one opsd.py, in this directory, and both hosts run it. They did not
# always: each host had its own copy, edited in place, and the two disagreed
# about where pi-2's key lived — so every pi-2 request signed with whatever key
# happened to be in the home the VM's copy named. A file that exists twice is a
# file that will differ.
#
#   bash scripts/devnet/deploy-opsd.sh vm
#   bash scripts/devnet/deploy-opsd.sh pi
#
# What differs between the hosts is configuration, not code, and all of it is
# in the case statement below: which validator's key the host holds, and what
# address the service may listen on.
set -euo pipefail

TARGET="${1:-}"
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/opsd.py"

case "$TARGET" in
  vm)
    SSH=(ssh -i "$HOME/.ssh/yamale_oracle" ubuntu@100.117.244.96)
    VALIDATOR="pi"
    # nginx is on this host, so the signer never needs to leave loopback.
    BIND="127.0.0.1"
    ;;
  pi)
    SSH=(ssh zubulmuk92@10.0.0.188 -p 2222)
    VALIDATOR="pi-2"
    # nginx is on the VM and has to cross the tailnet to reach this signer, so
    # loopback is not enough — but the tailnet address specifically, never a
    # wildcard, which would also publish it to the house LAN. Because the
    # socket is reachable from another machine, OPSD_AUTH is mandatory and the
    # service refuses to start without it.
    BIND="100.68.207.17"
    ;;
  *)
    echo "usage: $0 vm|pi" >&2
    exit 2
    ;;
esac

echo "=== deploying opsd.py to $TARGET (validator $VALIDATOR, bind $BIND) ==="

# Staged through the invoking user's home because /opt/yamale/bin is root-owned.
"${SSH[@]}" 'cat > /tmp/opsd.py' < "$SRC"
"${SSH[@]}" "sudo install -o root -g root -m 0755 /tmp/opsd.py /opt/yamale/bin/opsd.py && rm -f /tmp/opsd.py"

# The credential lives in an EnvironmentFile rather than the unit, because unit
# files are world-readable and this one is a password. Generated once and kept:
# rotating it here without updating the VM's nginx would break the pi-2 path.
"${SSH[@]}" "sudo install -d -m 0755 /etc/yamale"
"${SSH[@]}" "test -f /etc/yamale/opsd.env || sudo sh -c 'umask 077; printf \"OPSD_AUTH=opsd:%s\\n\" \"\$(head -c 24 /dev/urandom | base64 | tr -d /+=)\" > /etc/yamale/opsd.env'"
"${SSH[@]}" "sudo chmod 0600 /etc/yamale/opsd.env"

"${SSH[@]}" "sudo tee /etc/systemd/system/yamale-ops.service >/dev/null" <<UNIT
[Unit]
Description=Yamale ops service — signs for validator $VALIDATOR
After=network-online.target tailscaled.service
Wants=network-online.target

[Service]
ExecStart=/usr/bin/python3 /opt/yamale/bin/opsd.py
Environment=OPSD_VALIDATOR=$VALIDATOR
Environment=OPSD_BIND=$BIND
# Present on both hosts; ignored by the VM's copy, which is on loopback and
# behind nginx on the same machine.
EnvironmentFile=-/etc/yamale/opsd.env
Restart=always
# The Pi binds a tailscale0 address, which may not exist the instant the unit
# is first started after a reboot. Restarting into it beats ordering guesses.
RestartSec=5

[Install]
WantedBy=multi-user.target
UNIT

"${SSH[@]}" "sudo systemctl daemon-reload && sudo systemctl restart yamale-ops && sleep 2 && systemctl is-active yamale-ops"
"${SSH[@]}" "sudo journalctl -u yamale-ops -n 5 --no-pager"

# The nginx that fronts both signers is on the VM, so it is rewritten from the
# VM target — after the service, because it needs the credential the service
# will be checking.
#
# Both locations replace the operator's console credential with the service
# credential rather than forwarding it. Two separate questions are being asked:
# nginx asks which operator is calling, and logs the answer; opsd asks whether
# the caller is nginx at all. Keeping them separate means an operator's
# password can be rotated without touching the wire, and — the part that
# matters on the VM, where other services share the host — that reaching
# loopback:8086 is not by itself enough to sign with a validator's key.
if [ "$TARGET" = "vm" ]; then
  echo "=== rewriting the ops proxy ==="
  VM_AUTH=$("${SSH[@]}" "sudo sed -n 's/^OPSD_AUTH=//p' /etc/yamale/opsd.env")
  PI_AUTH=$(ssh zubulmuk92@10.0.0.188 -p 2222 "sudo sed -n 's/^OPSD_AUTH=//p' /etc/yamale/opsd.env")
  if [ -z "$VM_AUTH" ] || [ -z "$PI_AUTH" ]; then
    echo "missing a service credential — deploy the pi target first" >&2
    exit 1
  fi
  VM_B64=$(printf '%s' "$VM_AUTH" | base64 -w0)
  PI_B64=$(printf '%s' "$PI_AUTH" | base64 -w0)

  "${SSH[@]}" "sudo tee /etc/nginx/snippets/yamale-ops.conf >/dev/null" <<CONF
# Signing endpoints. Credentials are per validator, so an operator can only
# act as itself and the access log names who did it. Without this anyone who
# can reach the host can vote as a validator and freeze wallets.
#
# Generated by scripts/devnet/deploy-opsd.sh. The Authorization header each
# location sets is the service credential from that host's /etc/yamale/opsd.env,
# not an operator password.
location /api/ops/pi-2/ {
    auth_basic "Yamale — validator pi-2";
    auth_basic_user_file /etc/nginx/yamale-ops-pi2;
    # Across the tailnet: nginx is on this host, the signer is on the Pi, so
    # the Pi cannot lean on an nginx it does not run. It checks this itself.
    proxy_pass http://100.68.207.17:8086/;
    proxy_set_header Host \$host;
    proxy_set_header Authorization "Basic $PI_B64";
    proxy_read_timeout 70s;
    limit_req zone=yamale_rest burst=10 nodelay;
    access_log /var/log/nginx/yamale-ops.log;
}
location /api/ops/ {
    auth_basic "Yamale — validator pi";
    auth_basic_user_file /etc/nginx/yamale-ops-pi;
    proxy_pass http://127.0.0.1:8086/;
    proxy_set_header Host \$host;
    proxy_set_header Authorization "Basic $VM_B64";
    proxy_read_timeout 70s;
    limit_req zone=yamale_rest burst=10 nodelay;
    access_log /var/log/nginx/yamale-ops.log;
}
CONF
  "${SSH[@]}" "sudo nginx -t && sudo systemctl reload nginx && echo 'nginx reloaded'"
fi

echo "=== $TARGET done ==="
